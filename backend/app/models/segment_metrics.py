from __future__ import annotations

from decimal import Decimal
from typing import TYPE_CHECKING

from sqlalchemy import CheckConstraint, Computed, ForeignKey, Numeric, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base

if TYPE_CHECKING:
    from app.models.cycle_segment import CycleSegment


class SegmentMetrics(Base):
    """Per-segment aggregates computed by scripts/export_to_db.py (one row per cycle_segment)."""
    # Distances, solar and riders are written by the seed script; the flags below are generated.

    __tablename__ = "segment_metrics"
    __table_args__ = (
        CheckConstraint("solar_class IN ('niska', 'srednia', 'wysoka')", name="segment_metrics_solar_class_check"),
        CheckConstraint("cyclists_source IN ('vas_synthetic_match', 'class_median_assumed')",
                        name="segment_metrics_cyclists_source_check"),
    )

    segment_id: Mapped[int] = mapped_column(ForeignKey("cycle_segment.id", ondelete="CASCADE"), primary_key=True)
    fountain_dist_m: Mapped[Decimal | None] = mapped_column(Numeric(8, 1))
    ambici_dist_m: Mapped[Decimal | None] = mapped_column(Numeric(8, 1))
    facility_dist_m: Mapped[Decimal | None] = mapped_column(Numeric(8, 1))
    # Generated by the database from the distances; never write these.
    fountain_within_100m: Mapped[bool | None] = mapped_column(Computed("fountain_dist_m <= 100", persisted=True))
    fountain_within_300m: Mapped[bool | None] = mapped_column(Computed("fountain_dist_m <= 300", persisted=True))
    ambici_within_300m: Mapped[bool | None] = mapped_column(Computed("ambici_dist_m <= 300", persisted=True))
    water_access_flag: Mapped[str | None] = mapped_column(
        Text,
        Computed(
            "CASE WHEN fountain_dist_m IS NULL THEN NULL "
            "WHEN fountain_dist_m <= 100 THEN 'near_0_100m' "
            "WHEN fountain_dist_m <= 300 THEN 'medium_100_300m' "
            "ELSE 'far_over_300m' END",
            persisted=True,
        ),
    )
    solar_mean: Mapped[Decimal | None] = mapped_column(Numeric(8, 2))  # unitless working measure
    solar_median: Mapped[Decimal | None] = mapped_column(Numeric(8, 2))
    solar_max: Mapped[Decimal | None] = mapped_column(Numeric(8, 2))
    solar_valid_coverage: Mapped[Decimal | None] = mapped_column(Numeric(5, 4))
    solar_valid_pixels: Mapped[int | None]
    solar_class: Mapped[str | None] = mapped_column(Text)
    daily_cyclists_summer: Mapped[int | None]
    cyclists_source: Mapped[str | None] = mapped_column(Text)

    segment: Mapped[CycleSegment] = relationship(back_populates="metrics")
